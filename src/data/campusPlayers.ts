export const getCampusPlayerById = (id: string): CampusPlayer | undefined =>
  campusPlayers.find((p) => p.id === id);

export const getPlayersByRarity = (rarity: Rarity) =>
  campusPlayers.filter((p) => p.rarity === rarity);

export const getPlayersByPosition = (position: PlayerPosition) =>
  campusPlayers.filter((p) => p.position === position);

export const getPlayersByEra = (eraKeyword: string) =>
  campusPlayers.filter((p) => p.era.includes(eraKeyword));

export const sortPlayersByOverall = (ascending = false) =>
  [...campusPlayers].sort((a, b) =>
    ascending ? a.overall - b.overall : b.overall - a.overall
  );
